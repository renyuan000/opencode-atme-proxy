export interface WizardDefaults {
  configPath?: string;
  envPath?: string;
  nonInteractive?: boolean;
}

interface Answers {
  appId: string;
  appSecretFromQr: boolean;
  appSecret: string;
  meOpenId: string;
  approverOpenId: string;
  chatIds: string[];
  opencodeUrl: string;
  filterBaseUrl: string;
  filterModel: string;
  filterApiKey: string;
  projectWorktree: string;
  llmSource: "opencode" | "separate";
}

const CONFIG_DIR = join(homedir(), ".config", "opencode-atme-proxy");

export async function runSetup(defaults: WizardDefaults = {}): Promise<void> {
  const configPath = defaults.configPath ?? defaultConfigPath();
  const envPath = defaults.envPath ?? join(dirname(configPath), ".env");

  output.write("opencode-atme-proxy setup\n\n");
  output.write("本向导只写入本机配置，不会上传任何内容。\n");
  output.write(`配置: ${configPath}\n密钥: ${envPath}\n\n`);
  output.write("提示：open_id 是你在飞书里的用户 ID（ou_...）。\n");
  output.write("扫码创建应用时会自动带出，通常不用手填。\n\n");

  const existing = await readExisting(configPath);
  const answers = defaults.nonInteractive
    ? fromEnv(existing)
    : await ask(existing);

  if (defaults.nonInteractive) {
    const missing = [
      ["FEISHU_APP_ID", answers.appId],
      ["FEISHU_APP_SECRET", answers.appSecret],
      ["ATME_ME_OPEN_ID", answers.meOpenId],
    ].filter(([, value]) => !value).map(([key]) => key);
    if (missing.length > 0) {
      throw new Error(
        `非交互 setup 缺少环境变量: ${missing.join(", ")}。先 export 这些变量，或去掉 --yes 使用交互模式。`,
      );
    }
  }

  await mkdir(dirname(configPath), { recursive: true, mode: 0o700 });
  const config = buildConfig(existing, answers);
  const validated = AppConfigSchema.safeParse(config);
  if (!validated.success) {
    const details = validated.error.issues
      .map((issue) => `${issue.path.join(".") || "<root>"}: ${issue.message}`)
      .join("; ");
    throw new Error(`生成的配置未通过校验: ${details}`);
  }
  await writeFile(configPath, `${JSON.stringify(config, null, 2)}\n`, {
    encoding: "utf8",
    mode: 0o600,
  });
  await chmod(configPath, 0o600);

  const envLines = [
    "# generated by atme-proxy setup",
    `FEISHU_APP_ID=${answers.appId}`,
    `FEISHU_APP_SECRET=${answers.appSecret}`,
    `ATME_ME_OPEN_ID=${answers.meOpenId}`,
    `ATME_APPROVER_OPEN_IDS=${answers.approverOpenId}`,
    `ATME_OPENCODE_URL=${answers.opencodeUrl}`,
    ...(answers.filterBaseUrl ? [`ATME_FILTER_BASE_URL=${answers.filterBaseUrl}`] : []),
    ...(answers.filterModel ? [`ATME_FILTER_MODEL=${answers.filterModel}`] : []),
    ...(answers.filterApiKey ? [`ATME_FILTER_API_KEY=${answers.filterApiKey}`] : []),
    ...(answers.projectWorktree ? [`ATME_PROJECT_WORKTREE=${answers.projectWorktree}`] : []),
    "",
  ];
  await writeFile(envPath, envLines.join("\n"), { encoding: "utf8", mode: 0o600 });
  await chmod(envPath, 0o600);

  output.write(`\n已写入：\n  ${configPath}\n  ${envPath}\n\n`);
  if (answers.appSecretFromQr) {
    output.write("扫码已预填机器人能力、权限、事件和卡片回调。\n");
    output.write("仍需你完成：\n");
    output.write("  1. 管理员审批敏感权限 im:message.group_msg\n");
    output.write("  2. 发布应用\n");
    output.write("  3. 把机器人拉进目标群\n\n");
  }
  if (answers.chatIds.length === 0) {
    output.write("未配置群（正常）：先把机器人拉进群，再运行：\n");
    output.write("  atme-proxy chats --sync\n");
    output.write("它会自动发现群并写入 config。\n\n");
  }
  output.write("下一步：\n");
  output.write("  atme-proxy chats\n");
  output.write("  atme-proxy doctor\n");
  output.write("  atme-proxy agents\n");
  output.write("  atme-proxy start\n");
  output.write("\n开机自启（可选）：sudo bash deploy/systemd/install.sh（仓库根目录；详见 README 3.1）\n\n");
}

function maskIfSecret(label: string, value: string): string {
  if (/secret|key|password/i.test(label)) {
    return value ? "已设置" : "";
  }
  return value;
}

async function readExisting(path: string): Promise<Partial<AppConfig>> {
  try {
    const raw = await readFile(path, "utf8");
    return JSON.parse(raw) as AppConfig;
  } catch {
    return {};
  }
}

function fromEnv(existing: Partial<AppConfig>): Answers {
  const env = process.env;
  return {
    appId: env.FEISHU_APP_ID ?? existing.platforms?.feishu?.appId ?? "",
    appSecretFromQr: false,
    appSecret: env.FEISHU_APP_SECRET ?? "",
    meOpenId: env.ATME_ME_OPEN_ID ?? existing.platforms?.feishu?.me?.openId ?? "",
    approverOpenId:
      env.ATME_APPROVER_OPEN_IDS ??
      existing.platforms?.feishu?.approvers?.[0]?.openId ??
      env.ATME_ME_OPEN_ID ??
      existing.platforms?.feishu?.me?.openId ??
      "",
    chatIds:
      existing.platforms?.feishu?.groups?.map((group: { chatId: string }) => group.chatId) ?? [],
    opencodeUrl:
      env.ATME_OPENCODE_URL ?? existing.opencode?.baseUrl ?? "http://127.0.0.1:19876",
    filterBaseUrl: env.ATME_FILTER_BASE_URL ?? existing.filter?.baseUrl ?? "",
    filterModel: env.ATME_FILTER_MODEL ?? existing.filter?.model ?? "",
    filterApiKey: env.ATME_FILTER_API_KEY ?? "",
    projectWorktree: env.ATME_PROJECT_WORKTREE ?? existing.project?.worktree ?? "",
    llmSource: "separate",
  };
}

async function ask(existing: Partial<AppConfig>): Promise<Answers> {
  const rl = createInterface({ input, output });
  const askText = async (
    label: string,
    fallback: string,
    required = true,
  ): Promise<string> => {
    const hint = fallback ? ` [${maskIfSecret(label, fallback)}]` : "";
    const value = (await rl.question(`${label}${hint}: `)).trim();
    const result = value || fallback;
    if (required && !result) {
      rl.close();
      throw new Error(`${label} 不能为空`);
    }
    return result;
  };

  const feishu = existing.platforms?.feishu;
  let appId = "";
  let appSecret = "";
  let appSecretFromQr = false;
  let claimedOpenId = "";

  output.write(
    "\n选择应用凭证方式：\n" +
      "  1. 扫码自动创建飞书应用（推荐）\n" +
      "  2. 手动输入 App ID / App Secret\n",
  );
  const mode = (await rl.question("请选择 [1]: ")).trim() || "1";
  if (mode === "1") {
    let qrUrl = "";
    const result = await registerBotApp({
      onQrReady: (info) => {
        qrUrl = info.url;
        output.write(`\n用飞书扫一扫完成创建（${Math.round(info.expireIn / 60)} 分钟内有效）\n`);
        void (async () => {
          try {
            const qrcode = await import("qrcode");
            const text = await qrcode.toString(info.url, {
              type: "terminal",
              small: true,
              errorCorrectionLevel: "L",
              margin: 1,
            });
            output.write(`${text}\n`);
          } catch {
            // The link below is always printed as a fallback.
          }
          output.write("方式二（二维码扫不了时，在飞书里打开链接）：\n");
          output.write(`${info.url}\n`);
        })();
        output.write("等待飞书授权...\n");
      },
      onStatus: (info) => {
        if (info.status === "slow_down") {
          output.write(`飞书要求降低轮询频率，间隔 ${info.interval ?? "?"} 秒\n`);
        }
      },
    });
    appId = result.appId;
    appSecret = result.appSecret;
    appSecretFromQr = true;
    claimedOpenId = result.openId ?? "";
    output.write(`\n已创建机器人应用：${appId}\n`);
    if (!qrUrl) output.write("注意：没有拿到二维码链接，但授权已完成。\n");
  } else {
    appId = await askText("飞书 App ID (cli_...)", feishu?.appId ?? "");
    appSecret = await askText(
      "飞书 App Secret (留空则只写环境变量占位)",
      process.env.FEISHU_APP_SECRET ?? "",
      false,
    );
  }
  const meOpenId =
    claimedOpenId ||
    (await askText("你的 open_id (ou_...)", feishu?.me?.openId ?? ""));
  const approverOpenId =
    claimedOpenId ||
    (await askText(
      "审批人 open_id (回车等于你自己)",
      feishu?.approvers?.[0]?.openId ?? meOpenId,
    ));
  output.write(
    "\n群先不用填。机器人进群后运行 atme-proxy chats --sync 会自动发现并写入。\n\n",
  );
  const chatIdsRaw = await askText(
    "群 chat_id (可留空，回车跳过)",
    feishu?.groups?.map((group: { chatId: string }) => group.chatId).join(",") ?? "",
    false,
  );
  const opencodeUrl = await askText(
    "OpenCode 服务地址",
    existing.opencode?.baseUrl ?? "http://127.0.0.1:19876",
  );

  output.write(
    "\n关于“配置 LLM”：\n" +
      "  OpenCode 已配置的模型用于群回复、任务分析、开发执行。\n" +
      "  批量筛选建议单独配一个低成本 OpenAI 兼容模型，避免用主模型烧钱。\n" +
      "  如果你不想单独配，可让筛选也走 OpenCode，但本期需要填 baseUrl/model。\n\n",
  );
  const filterBaseUrl = await askText(
    "低成本模型 baseUrl (OpenAI 兼容，含 /v1)",
    existing.filter?.baseUrl ?? "",
    false,
  );
  const filterModel = await askText(
    "低成本模型名",
    existing.filter?.model ?? "",
    false,
  );
  const filterApiKey = await askText(
    "低成本模型 API Key (只写入 .env)",
    process.env.ATME_FILTER_API_KEY ?? "",
    false,
  );
  const projectWorktree = await askText(
    "主项目代码目录绝对路径",
    existing.project?.worktree ?? process.cwd(),
    false,
  );
  rl.close();

  return {
    appId,
    appSecretFromQr,
    appSecret,
    meOpenId,
    approverOpenId,
    chatIds: chatIdsRaw
      .split(/[,，\s]+/)
      .map((item) => item.trim())
      .filter(Boolean),
    opencodeUrl,
    filterBaseUrl,
    filterModel,
    filterApiKey,
    projectWorktree,
    llmSource: filterBaseUrl && filterModel ? "separate" : "opencode",
  };
}

function buildConfig(existing: Partial<AppConfig>, answers: Answers): AppConfig {
  const base = structuredClone(existing) as Record<string, any>;
  base.version = base.version ?? 1;
  base.app = {
    stateDir: "~/.local/state/opencode-atme-proxy",
    logLevel: "info",
    ...(base.app ?? {}),
  };
  base.platforms = base.platforms ?? {};
  base.platforms.feishu = {
    enabled: true,
    appId: answers.appId,
    appSecretEnv: "FEISHU_APP_SECRET",
    domain: "feishu",
    me: { openId: answers.meOpenId, name: "我" },
    approvers: [{ openId: answers.approverOpenId, name: "我" }],
    bootstrap: {
      claimCodeEnv: "ATME_CLAIM_CODE",
      allowPrivateClaim: false,
      maxClaimAttemptsPer10Min: 5,
    },
    groups: answers.chatIds.map((chatId) => ({
      chatId,
      name: chatId,
      enabled: true,
    })),
    receiveAllGroupMessages: false,
    rateLimit: { sendPerSecond: 5, burst: 10 },
    ...(base.platforms.feishu ?? {}),
  };
  base.filter = base.filter ?? {};
  base.filter.enabled = Boolean(answers.filterBaseUrl && answers.filterModel);
  if (answers.filterBaseUrl) base.filter.baseUrl = answers.filterBaseUrl;
  if (answers.filterModel) base.filter.model = answers.filterModel;
  base.filter.apiKeyEnv = "ATME_FILTER_API_KEY";
  base.opencode = {
    ...(base.opencode ?? {}),
    baseUrl: answers.opencodeUrl,
    passwordEnv: "ATME_OPENCODE_PASSWORD",
    sessionTitlePrefix: "atme",
    keepSessions: true,
    sessionListVisible: true,
  };
  base.project = {
    ...(base.project ?? {}),
    mode: answers.projectWorktree ? "explicit" : "auto",
    ...(answers.projectWorktree ? { worktree: answers.projectWorktree } : {}),
  };
  return base as AppConfig;
}

export interface DoctorCheck {
  ok: boolean;
  label: string;
  detail?: string;
  fix?: string;
}

export async function runDoctor(configPath?: string): Promise<DoctorCheck[]> {
  const checks: DoctorCheck[] = [];
  const path = configPath ?? defaultConfigPath();

  let loaded: Awaited<ReturnType<typeof loadConfig>> | undefined;
  try {
    loaded = await loadConfig({ path, enforcePermissions: false });
    checks.push({ ok: true, label: "配置文件", detail: path });
    const mode = (await stat(path)).mode & 0o777;
    checks.push({
      ok: (mode & 0o077) === 0,
      label: "配置权限",
      detail: `mode ${mode.toString(8)}`,
      fix: (mode & 0o077) !== 0 ? `chmod 600 ${path}` : undefined,
    });
  } catch (error) {
    checks.push({
      ok: false,
      label: "配置文件",
      detail: toErrorMessage(error),
      fix: "运行 atme-proxy setup",
    });
    return checks;
  }

  const feishu = loaded.config.platforms.feishu;
  checks.push({
    ok: feishu.appId.startsWith("cli_"),
    label: "App ID 格式",
    detail: feishu.appId,
    fix: feishu.appId.startsWith("cli_") ? undefined : "App ID 应以 cli_ 开头",
  });
  checks.push({
    ok: !!loaded.secrets.appSecret,
    label: "App Secret",
    detail: loaded.secrets.appSecret ? "已设置" : "缺失",
    fix: loaded.secrets.appSecret ? undefined : "在 .env 设置 FEISHU_APP_SECRET",
  });

  if (loaded.secrets.appSecret) {
    try {
      const client = new Lark.Client({
        appId: feishu.appId,
        appSecret: loaded.secrets.appSecret,
        domain: feishu.domain === "lark" ? Lark.Domain.Lark : Lark.Domain.Feishu,
        logger: { error: () => {}, warn: () => {}, info: () => {}, debug: () => {}, trace: () => {} },
      });
      const info: any = await client.request({ method: "GET", url: "/open-apis/bot/v3/info" });
      const botOpenId = info?.bot?.open_id ?? info?.data?.bot?.open_id;
      if (info?.code !== 0) {
        checks.push({
          ok: false,
          label: "飞书凭据",
          detail: `App Secret 无效或应用未发布: ${info?.msg ?? info?.code ?? "unknown"}`,
          fix: "核对 App ID/Secret，并在开放平台发布应用",
        });
      } else if (!botOpenId) {
        checks.push({
          ok: false,
          label: "机器人能力",
          detail: "凭据有效，但应用没有机器人能力",
          fix: "在开放平台开启机器人能力并发布",
        });
      } else {
        checks.push({
          ok: true,
          label: "飞书凭据与机器人",
          detail: `bot open_id=${botOpenId}`,
        });
        const chatId = feishu.groups[0]?.chatId;
        if (chatId) {
          const now = Date.now();
          try {
            await client.request({
              method: "GET",
              url: "/open-apis/im/v1/messages",
              params: {
                container_id_type: "chat",
                container_id: chatId,
                start_time: String(Math.floor((now - 300_000) / 1000)),
                end_time: String(Math.floor(now / 1000)),
                page_size: 1,
              },
            });
            checks.push({ ok: true, label: "历史消息权限", detail: "可用" });
          } catch (error) {
            const data = (error as { response?: { data?: { msg?: string } } }).response?.data;
            checks.push({
              ok: false,
              label: "历史消息权限",
              detail: data?.msg ?? toErrorMessage(error),
              fix: "开放平台添加 im:message:readonly（或 im:message）并发布",
            });
          }
        }
        try {
          await client.request({
            method: "GET",
            url: "/open-apis/im/v1/chats",
            params: { page_size: 1 },
          });
          checks.push({ ok: true, label: "群列表权限", detail: "可用" });
        } catch (error) {
          const data = (error as { response?: { data?: { msg?: string } } }).response?.data;
          checks.push({
            ok: false,
            label: "群列表权限",
            detail: data?.msg ?? toErrorMessage(error),
            fix: "开放平台添加 im:chat:readonly（或 im:chat）并发布",
          });
        }
      }
    } catch (error) {
      checks.push({
        ok: false,
        label: "飞书凭据",
        detail: toErrorMessage(error),
        fix: "检查网络、App ID/Secret，以及应用是否已发布",
      });
    }
  }
  checks.push({
    ok: !!feishu.me.openId || !!feishu.approvers[0]?.openId,
    label: "owner（我）",
    detail: feishu.me.openId ?? feishu.approvers[0]?.openId ?? "未设置",
    fix: "设置 platforms.feishu.me.openId 或私聊 claim code",
  });
  checks.push({
    ok: feishu.groups.length > 0,
    label: "群白名单",
    detail:
      feishu.groups.length > 0
        ? feishu.groups
            .map((group) => (group.name && group.name !== group.chatId ? `${group.name} (${group.chatId})` : group.chatId))
            .join(", ")
        : "0 个群",
    fix:
      feishu.groups.length > 0
        ? undefined
        : "先把机器人拉进群，再运行 atme-proxy chats --sync",
  });

  try {
    const client = createOpencodeClient({ baseUrl: loaded.config.opencode.baseUrl });
    const result = await client.provider.list({});
    if (result.error || !result.data) throw new Error("provider.list failed");
    const connected = result.data.connected ?? [];
    checks.push({
      ok: true,
      label: "OpenCode 服务",
      detail: loaded.config.opencode.baseUrl,
    });
    checks.push({
      ok: connected.length > 0,
      label: "OpenCode 模型",
      detail: connected.length > 0 ? connected.join(", ") : "没有已连接的 provider",
      fix:
        connected.length > 0
          ? undefined
          : "在 OpenCode 里配置并登录一个 provider，或检查 opencode.json",
    });
    const subagentModels = result.data.all
      .filter((provider) => connected.includes(provider.id))
      .flatMap((provider) =>
        Object.values(provider.models ?? {}).map((model) => `${provider.id}/${model.id}`),
      );
    checks.push({
      ok: subagentModels.length > 0,
      label: "可用模型",
      detail: subagentModels.slice(0, 5).join(", "),
    });
  } catch (error) {
    checks.push({
      ok: false,
      label: "OpenCode 服务",
      detail: toErrorMessage(error),
      fix: `启动 opencode serve --port 19876`,
    });
  }

  if (loaded.config.filter.enabled) {
    checks.push({
      ok: Boolean(loaded.config.filter.baseUrl && loaded.config.filter.model),
      label: "筛选模型配置",
      detail: `${loaded.config.filter.baseUrl ?? "?"} / ${loaded.config.filter.model ?? "?"}`,
    });
    checks.push({
      ok: Boolean(loaded.secrets.filterApiKey),
      label: "筛选模型 API Key",
      detail: loaded.secrets.filterApiKey ? "已设置" : "缺失",
      fix: "在 .env 设置 ATME_FILTER_API_KEY",
    });
  } else {
    checks.push({
      ok: true,
      label: "筛选模型配置",
      detail: "未启用；@ 消息仍会走 OpenCode 主模型",
    });
  }

  const worktree = loaded.config.project.worktree;
  let worktreeOk = false;
  let worktreeDetail = "未设置，将自动解析";
  if (worktree) {
    try {
      const info = await stat(worktree);
      worktreeOk = info.isDirectory();
      worktreeDetail = worktree;
    } catch {
      worktreeDetail = `目录不存在: ${worktree}`;
    }
  } else {
    worktreeOk = true;
  }
  checks.push({
    ok: worktreeOk,
    label: "项目目录",
    detail: worktreeDetail,
    fix: worktreeOk ? undefined : "设置 project.worktree 为存在的仓库绝对路径",
  });

  return checks;
}
